void Sound_Out(uint32_t data){
  GPIOB->DOUTCLR31_0 = 31;
  GPIOB->DOUT31_0 |= data;
}

void Sound_Init(void){
  IOMUX->SECCFG.PINCM[PB0INDEX] = 0x00000081;
  IOMUX->SECCFG.PINCM[PB1INDEX] = 0x00000081;
  IOMUX->SECCFG.PINCM[PB2INDEX] = 0x00000081;
  IOMUX->SECCFG.PINCM[PB3INDEX] = 0x00000081;
  IOMUX->SECCFG.PINCM[PB4INDEX] = 0x00000081;
  GPIOB->DOE31_0 |= 31;

  SoundIndex = 0;
  CurrentTrack = 0;
  Sound_Out(0);
}

void Sound_Start(uint32_t period){
  SysTick->CTRL = 0;
  SysTick->LOAD = period - 1;
  SysTick->VAL = 0;
  SCB->SHP[1] = (SCB->SHP[1] & (~0xC0000000)) | (2<<30);
  SysTick->CTRL = 7;
}

extern "C" void SysTick_Handler(void);
void SysTick_Handler(void){ // called at 11 kHz
  if(!CurrentTrack) {Sound_Out(0); return;}
  Sound_Out(CurrentTrack->sample[SoundIndex]);
  SoundIndex++;
  if(SoundIndex >= CurrentTrack->size){
    SoundIndex = 0;
    CurrentTrack = 0;
    Sound_Out(0);
  }
}

void Play_Audio(int trackid){
  CurrentTrack = &TrackList[trackid];
  SoundIndex = 0;
}
